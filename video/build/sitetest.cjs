const { chromium, devices } = require(process.env.PW_PATH || "playwright");
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
  const errs = [];
  p.on("pageerror", (e) => errs.push("PAGEERROR " + e.message));
  p.on("console", (m) => m.type() === "error" && errs.push("CONSOLE " + m.text()));
  const out = "video/out/site/";
  await p.goto("http://localhost:8765/#/start"); await p.waitForTimeout(2500); await p.screenshot({ path: out + "1_start.png" });
  await p.goto("http://localhost:8765/#/audit-hash-chain"); await p.waitForTimeout(2000);
  const fr = p.frames().find((f) => f.url().includes("stage.html"));
  await fr.click("#big"); await p.waitForTimeout(6000); await p.screenshot({ path: out + "2_chapter_playing.png" });
  console.log("player time:", await fr.evaluate("master.time().toFixed(1)"), "caption:", (await fr.evaluate("document.getElementById('cap').textContent")).slice(0, 40));
  await p.evaluate(() => window.scrollTo(0, 1500)); await p.waitForTimeout(300); await p.screenshot({ path: out + "3_chapter_notes.png" });
  await p.click(".quiz button"); 
  await p.goto("http://localhost:8765/#/playground"); await p.waitForTimeout(500);
  console.log("verdict0:", await p.textContent(".verdict"));
  await p.fill('input[data-i="1"]', "UPDATE grade B -> B (student b23101)"); await p.press('input[data-i="1"]', "Tab"); await p.waitForTimeout(200);
  console.log("verdict1:", await p.textContent(".verdict"));
  await p.click("[data-forge]"); await p.waitForTimeout(200);
  console.log("verdict2:", await p.textContent(".verdict"));
  await p.screenshot({ path: out + "4_playground.png" });
  await p.goto("http://localhost:8765/#/interview"); await p.waitForTimeout(400); await p.fill("#qs", "index");
  console.log("interview hits for 'index':", await p.locator("#ql details").count());
  await p.click("#askBtn"); await p.fill("#chatIn", "PgBouncer transaction mode kya hota hai?"); await p.press("#chatIn", "Enter"); await p.waitForTimeout(500);
  await p.fill("#chatIn", "cricket kaun jeeta"); await p.press("#chatIn", "Enter"); await p.waitForTimeout(300);
  await p.screenshot({ path: out + "5_chat.png" });
  console.log("bot msgs:", await p.locator(".m.b").count(), "| first answer:", (await p.locator(".m.b").nth(1).textContent()).slice(0, 90));
  await p.goto("http://localhost:8765/#/map"); await p.waitForTimeout(400); await p.screenshot({ path: out + "6_map.png" });
  const m = await b.newPage({ ...devices["Pixel 7"] });
  await m.goto("http://localhost:8765/#/redis"); await m.waitForTimeout(2000); await m.screenshot({ path: out + "7_mobile.png" });
  console.log("mobile overflow px:", await m.evaluate("document.documentElement.scrollWidth - innerWidth"));
  console.log(errs.length ? errs.join("\n") : "no page errors");
  await b.close();
})();
